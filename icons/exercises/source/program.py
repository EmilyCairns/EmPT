def T(pts, w=3):                      # tint (machine / bench frame)
    return L(pts, w, "tint")
def TR(x, y, w, h, rx=2.5):
    return Rect(x, y, w, h, rx, "tint")
def Band(d, w=2.2):
    return Path(d, w, "accent")
def DBs(x, y):                        # small horizontal dumbbell, handle x..x+5
    return [A([(x, y), (x + 5, y)], 2.2), Rect(x - 1.6, y - 3.6, 3.2, 7.2, 1.6), Rect(x + 3.4, y - 3.6, 3.2, 7.2, 1.6)]
def DBV(cx, cy):                      # vertical dumbbell
    return [A([(cx, cy - 3), (cx, cy + 3)], 2.2), Rect(cx - 3.6, cy - 5, 7.2, 3.2, 1.6), Rect(cx - 3.6, cy + 1.8, 7.2, 3.2, 1.6)]
def Roller(cx, cy, r=4):
    return [Disc(cx, cy, r), Ring(cx, cy, r - 1.9, 1.1, "paper")]
def Arrow(x1, y, x2):                 # horizontal accent arrow pointing to x2
    d = 1 if x2 > x1 else -1
    return [A([(x1, y), (x2, y)]), A([(x2 - 3.4 * d, y - 3.4), (x2, y), (x2 - 3.4 * d, y + 3.4)])]
